#异常（也称为bug），就是程序运行过程中出现的错误，他会中断程序的正常执行流程。
'''
作用：
1.保证数据，逻辑的正确性，避免程序执行混乱
2.在开发阶段，尽量发现更多的问题，尽早解决问题，保障程序正常执行

程序运行过程中出现异常，有两种处理方案：
1.不做处理：整个程序因为一个bug，中断执行（之前编程的程序）
2.捕获异常：按照我们自己的处理方式，处理完异常，程序继续执行（编写程序时，做好预案，出现异常，按照预案处理）

如何让在代码当中捕获异常：  try
try的用法：
    try:
        可能出现异常的业务代码1
        可能出现异常的业务代码2
    except[异常类型 as 变量名]#括号内也可以不写，写了就是捕获指定目标类型的异常后执行异常出现后的预案
        出现异常时的预案
    [finally:
        不管是否会出现异常，都会执行的代码]#这一段是可以不写的，

'''

try:
    print("================")
    print(1/0)
    print(my_name)

    print("================")
except NameError as e:
    print("程序运行报错，错误信息",e)
except ZeroDivisionError as e:
    print("程序运行报错，错误信息",e)
finally:
    print("释放资源~")

