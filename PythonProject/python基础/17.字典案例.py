# 开发一个购物车管理系统，实现商品信息的添加、修改、删除、查询功能。
# 系统使用字典结构存储商品数据，通过控制台菜单与用户交互。
# 功能需求：
# 1. 添加购物车：用户根据提示录入商品名称、以及该商品的价格、数量，保存该商品信息到购物车。
# 2. 修改购物车：要求用户输入要修改的购物车商品名称，然后再提示输入该商品的价格、数量，输入完成后修改该商品信息。
# 3. 删除购物车：要求用户输入要删除的购物车名称，根据名称删除购物车中的商品。
# 4. 查询购物车：将购物车中的商品信息展示出来，格式为："商品名称：xxx，商品价格：xxx，商品数量：xxx"。
# 5. 退出购物车

#1.创建购物车列表
shop_dict = {}
#2.生成控制台菜单
print("#######购物车系统#######")
print("1.添加购物车\n2.修改购物车\n3.删除购物车\n4.查询购物车\n5，退出购物车")
print("#######################")
#3.根据用户输入的数字来执行操作
while True:
    chose = int(input("请选择要执行的操作："))
    match chose:
        case 1:
            a = input("请输入商品名称:")
            b = input("请输入商品价格:")
            c = input("请输入商品数量:")
            shop_dict[a] = {"价格": b, "数量": c}
            print("已成功添加商品")
        case 2:
            a = input("输入你想要修改的商品名称：")
            b = input("输入你想要修改的商品价格：")
            c = input("输入你想要修改的商品数量：")
            shop_dict[a] = {"价格": b, "数量": c}
        case 3:
            a = input("输入你想要删除的商品名称：")
            del shop_dict[a]
        case 4:
            d = shop_dict.items()
            print(d)
        case 5:
            break
        case _:
            print("请输入正确的数字")
            continue







