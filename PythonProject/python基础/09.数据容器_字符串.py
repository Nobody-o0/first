#字符串是字符的容器，特点：无法修改,有序性,可迭代性。字符串也有索引，同样可以通过索引来获取对应的元素
s = "hello world"
print(s[4])
print(s[-3])
#切片操作
s_cute = s[0:5:1]
print(s_cute)

#字符串的常用方法
#find():查找字符串，返回第一次出现的索引位置，找不到返回-1
#count():统计字符串出现的次数
#upper()：将字符串中所有字母转换成大写
#lower():将字符串中的所有字母转换为小写
#split()：将字符串按指定分隔符分割成列表
#strip():去除字符串两端的空白字符或指定字符
#replace()：将字符串中的指定字串替换为新的子串
#startswith():检查字符串是否以指定子串开头，返回布尔值
#endswith():检查字符串是否以指定的字符串结尾，返回布尔值