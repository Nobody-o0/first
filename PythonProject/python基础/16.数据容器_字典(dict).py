#字典(dict):
'''
字典(dict)中存储的是键值对(key : value)类型的数据，可以根据键(key)找到对应的值(value)，
其他语言体系里有的会称其为:
哈希表（hash）
映射（map）
'''
#特点: 1.键（key）和值（value）一一对应，可以根据键(key)找到对应的值(value)
#-----2.键（key）不能重复,若重复了，后面的值会覆盖前面的值，
#-----3.value可以是任意类型的值，但key必须是不可变类型（不能是list,dict,set）
#字典的定义：
dict1 = {"王林":675,"李沐湾":608,"徐立国":459}
#字典的基本操作
#1.访问
print(f"李沐湾:{dict1["李沐湾"]}")


'''
1.添加
字典名称[key] = value------往指定字典中添加key-value键值对--------------dict1["涛哥"] = 688
2.删除
字典名称.pop(key)----------删除字典中指定的key，并返回该key对应的value----score = dict1.pop("涛哥")
del 字典名称[key]----------删除字典中指定的键值对-----------------------del dict1["涛哥"]
3.修改
字典名称[key] = value------修改字典中指定的key对应的值-------------------dict1["小智"] = 658
4.查询
字典名称[key]--------------根据key获取value---------------------------dict1["涛哥"]
字典名称.get(key)----------根据key获取value---------------------------dict1.get("涛哥")
字典名称.keys()------------获取所有的key------------------------------dict1.keys()
字典名称.values()----------获取所有的value----------------------------dict1.values()
字典名称.items()-----------获取所有的key-value键值对-------------------dict1.items()
'''